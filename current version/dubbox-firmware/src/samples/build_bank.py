"""Reproducibly convert verified CC0 VCSL WAVs into the compact Studio bank.
Requires Python3 and NumPy. Run fetch_vcsl.py first. No generated/synthetic sound.
"""
from pathlib import Path
import wave,struct,hashlib,json,shutil
import numpy as np
import argparse
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--cache',type=Path,required=True,help='Source cache prepared by fetch_sources.py')
parser.add_argument('--wav-dir',type=Path,required=True,help='Output folder for auditable WAVs and manifest')
args=parser.parse_args()
BASE=args.cache.resolve()
OUT=args.wav_dir.resolve()
BANK=Path(__file__).resolve().parent
RATE=44100
ORDER=['kick','snare','clap','closed_hat','open_hat','low_tom','rim','perc']
manifest=json.load(open(BASE/'source-manifest.json'))
for p in [OUT,BANK,OUT/'wav']:p.mkdir(parents=True,exist_ok=True)
def read_wave(path):
 b=path.read_bytes();chunks={};o=12
 assert b[:4]==b'RIFF' and b[8:12]==b'WAVE'
 while o+8<=len(b):
  n=struct.unpack_from('<I',b,o+4)[0];chunks[b[o:o+4]]=b[o+8:o+8+n];o+=8+n+(n&1)
 code,channels,sr,_,_,bits=struct.unpack_from('<HHIIHH',chunks[b'fmt ']);raw=chunks[b'data']
 if code==1 and bits==16:a=np.frombuffer(raw,dtype='<i2').astype(np.float64)/32768
 elif code==1 and bits==24:
  z=np.frombuffer(raw,dtype='u1').reshape(-1,3);v=z[:,0].astype(np.int32)|(z[:,1].astype(np.int32)<<8)|(z[:,2].astype(np.int32)<<16);a=np.where(v&0x800000,v-0x1000000,v)/8388608
 elif code==3 and bits==32:a=np.frombuffer(raw,dtype='<f4').astype(np.float64)
 else:raise ValueError((path,code,bits))
 return a.reshape(-1,channels).mean(axis=1),sr,channels,bits
samples=[]
for x in manifest['samples']:
 path=BASE/'raw'/f"{x['name']}.wav";assert hashlib.sha256(path.read_bytes()).hexdigest()==x['sha256']
 a,sr,ch,bits=read_wave(path);original_frames=len(a)
 # Remove the recording's constant DC bias, not the musical low frequencies.
 a-=np.mean(a)
 peak=np.max(np.abs(a));nz=np.flatnonzero(np.abs(a)>max(peak*.001,1/32768))
 start=max(0,int(nz[0])-round(sr*.002)) if len(nz) else 0
 maxsecs=8.0 if x['kind']=='piano' else len(a)/sr
 a=a[start:start+round(sr*maxsecs)]
 # Preserve44.1k recordings exactly in time; filter only if downsampling.
 if sr>RATE:
  cutoff=20000;n=np.arange(257)-128
  kernel=2*cutoff/sr*np.sinc(2*cutoff/sr*n)*np.hamming(257);kernel/=kernel.sum()
  a=np.convolve(np.pad(a,(128,128)),kernel,mode='valid')
 if sr!=RATE:a=np.interp(np.arange(round(len(a)*RATE/sr))*sr/RATE,np.arange(len(a)),a)
 # Preserve the attack; small fade-in and equal-power tail avoid cut clicks.
 attack=min(len(a),round(RATE*.001));a[:attack]*=np.linspace(0,1,attack)
 fade=min(len(a)//3,round(RATE*(1.0 if x['kind']=='piano' else .03)))
 a[-fade:]*=np.cos(np.linspace(0,np.pi/2,fade))**2
 gain=.75/max(np.max(np.abs(a)),1e-12);a*=gain
 pcm=np.rint(a*32767).astype('<i2');pcm[0]=pcm[-1]=0
 assert len(pcm)>2 and np.max(np.abs(pcm.astype(np.int32)))<=24576
 wav=OUT/'wav'/f"{x['name']}.wav"
 with wave.open(str(wav),'wb') as w:w.setparams((1,2,RATE,0,'NONE','not compressed'));w.writeframes(pcm.tobytes())
 x.update(output_frames=len(pcm),output_rate=RATE,source_rate=sr,source_channels=ch,source_bits=bits,source_frames=original_frames,trim_start_frames=start,gain=float(gain),output_sha256=hashlib.sha256(pcm.tobytes()).hexdigest(),wav_sha256=hashlib.sha256(wav.read_bytes()).hexdigest(),output_seconds=len(pcm)/RATE)
 samples.append((x,pcm))
 print(x['name'],x['root_midi'],len(pcm),float(np.max(np.abs(a))))
# Verify named piano pitch through autocorrelation near each expected root.
for x,pcm in samples:
 if x['kind']!='piano':continue
 a=pcm.astype(float)[int(.08*RATE):int(.7*RATE)]
 expected=440*2**((x['root_midi']-69)/12);period=RATE/expected
 lags=range(max(1,int(period*.96)),int(period*1.04)+2)
 scores=[np.dot(a[:-lag],a[lag:])/np.sqrt(np.dot(a[:-lag],a[:-lag])*np.dot(a[lag:],a[lag:])) for lag in lags]
 best=list(lags)[int(np.argmax(scores))];hz=RATE/best
 x['pitch_check_hz']=hz;assert abs(12*np.log2(hz/expected))<.6,(x['name'],hz,expected)
header='''#pragma once
#include <stdint.h>
namespace studio_samples {
struct Sample { const int16_t* pcm; uint32_t frames; uint16_t sampleRate; uint8_t rootMidi; };
constexpr uint8_t kPianoCount = 5;
constexpr uint8_t kDrumCount = 8;
extern const Sample piano[kPianoCount];
// Kick, snare, clap, closed hat, open hat, tom, rim, tambourine.
extern const Sample drums[kDrumCount];
}
'''
(BANK/'studio_samples.h').write_text(header)
with open(BANK/'studio_samples.cpp','w') as f:
 f.write('// Generated by build_bank.py from verified VCSL CC0 recordings; see README.md.\n#include "studio_samples.h"\n#if defined(ARDUINO)\n#include <Arduino.h>\n#else\n#define PROGMEM\n#endif\nnamespace studio_samples {\nnamespace {\n')
 for x,pcm in samples:
  f.write(f"alignas(4) const int16_t {x['name']}_pcm[] PROGMEM = {{\n")
  for i in range(0,len(pcm),24):f.write(','.join(map(str,pcm[i:i+24]))+',\n')
  f.write('};\n')
 f.write('}\n')
 for group,names in [('piano',[f'piano_c{i}' for i in range(1,6)]),('drums',ORDER)]:
  f.write(f'const Sample {group}[{len(names)}] = {{\n')
  for name in names:
   x,pcm=next((x,pcm) for x,pcm in samples if x['name']==name)
   f.write(f"  {{{name}_pcm, {len(pcm)}, {RATE}, {x['root_midi']}}},\n")
  f.write('};\n')
 f.write('}\n')
manifest['pcm_bytes']=sum(len(pcm)*2 for x,pcm in samples);assert manifest['pcm_bytes']<6*1024*1024
manifest['processing']='Mono average; DC mean removal; onset trim preserving 2ms; Native44100 kept; higher source rates use257tap Hamming-windowed-sinc20kHz antialiasing then resample44100; 1msattack fade; piano1s/drum30ms cappedtailfade; piano8s max, drums full originaltail; per-samplepeak0.75; signed16-bit PCM'
for p in [OUT,BANK]:
 (p/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n');shutil.copy(BASE/'VCSL-LICENSE',p/'LICENSE-VCSL-CC0.txt')
print('PCM_BYTES',manifest['pcm_bytes'])
